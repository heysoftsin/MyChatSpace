-- PrivateChat database setup for Supabase
-- Run this entire file in Supabase > SQL Editor.
-- Then enable Authentication > Providers > Anonymous Sign-Ins.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  created_at timestamptz not null default now(),
  constraint username_format check (username ~ '^[a-z0-9_.]{3,24}$')
);

create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 40),
  code text not null unique,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.room_members (
  room_id uuid not null references public.rooms(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (room_id, user_id)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text check (body is null or char_length(body) <= 4000),
  image_url text,
  created_at timestamptz not null default now(),
  constraint message_has_content check (
    nullif(trim(coalesce(body, '')), '') is not null or image_url is not null
  )
);

create table if not exists public.room_invites (
  id uuid primary key default gen_random_uuid(),
  room_id uuid not null references public.rooms(id) on delete cascade,
  inviter_id uuid not null references public.profiles(id) on delete cascade,
  invitee_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(room_id, invitee_id)
);

create index if not exists messages_room_created_idx on public.messages(room_id, created_at);
create index if not exists room_members_user_idx on public.room_members(user_id);
create index if not exists profiles_username_idx on public.profiles(username);

-- Random 8-character room codes.
create or replace function public.make_room_code()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  candidate text;
begin
  loop
    candidate := upper(substr(encode(gen_random_bytes(6), 'hex'), 1, 8));
    exit when not exists (select 1 from public.rooms where code = candidate);
  end loop;
  return candidate;
end;
$$;

create or replace function public.create_room(room_name text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  new_room uuid;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;
  if not exists (select 1 from public.profiles where id = auth.uid()) then
    raise exception 'Profile not found';
  end if;

  insert into public.rooms(name, code, created_by)
  values (trim(room_name), public.make_room_code(), auth.uid())
  returning id into new_room;

  insert into public.room_members(room_id, user_id)
  values (new_room, auth.uid());

  return new_room;
end;
$$;

create or replace function public.join_room_by_code(room_code_input text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  target_room uuid;
begin
  if auth.uid() is null then raise exception 'Not signed in'; end if;

  select id into target_room
  from public.rooms
  where code = upper(trim(room_code_input));

  if target_room is null then raise exception 'Room code not found'; end if;

  insert into public.room_members(room_id, user_id)
  values (target_room, auth.uid())
  on conflict do nothing;

  return target_room;
end;
$$;

grant execute on function public.create_room(text) to authenticated;
grant execute on function public.join_room_by_code(text) to authenticated;

-- RLS
alter table public.profiles enable row level security;
alter table public.rooms enable row level security;
alter table public.room_members enable row level security;
alter table public.messages enable row level security;
alter table public.room_invites enable row level security;

-- Profiles: usernames are public so people can invite by username.
create policy "profiles are viewable by signed in users"
on public.profiles for select to authenticated using (true);

create policy "users create their own profile"
on public.profiles for insert to authenticated with check (id = auth.uid());

create policy "users update their own profile"
on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Rooms can only be viewed by members.
create policy "members can view rooms"
on public.rooms for select to authenticated
using (
  exists (
    select 1 from public.room_members rm
    where rm.room_id = rooms.id and rm.user_id = auth.uid()
  )
);

-- Room membership: users can see memberships for rooms they belong to.
create policy "members can view room members"
on public.room_members for select to authenticated
using (
  exists (
    select 1 from public.room_members own
    where own.room_id = room_members.room_id and own.user_id = auth.uid()
  )
);

create policy "users can join rooms"
on public.room_members for insert to authenticated
with check (user_id = auth.uid());

-- Messages only inside rooms the user belongs to.
create policy "members can read messages"
on public.messages for select to authenticated
using (
  exists (
    select 1 from public.room_members rm
    where rm.room_id = messages.room_id and rm.user_id = auth.uid()
  )
);

create policy "members can send messages"
on public.messages for insert to authenticated
with check (
  sender_id = auth.uid()
  and exists (
    select 1 from public.room_members rm
    where rm.room_id = messages.room_id and rm.user_id = auth.uid()
  )
);

-- Invites: inviter can create for a room they belong to; invitee can see their own.
create policy "room members can create invites"
on public.room_invites for insert to authenticated
with check (
  inviter_id = auth.uid()
  and exists (
    select 1 from public.room_members rm
    where rm.room_id = room_invites.room_id and rm.user_id = auth.uid()
  )
  and invitee_id <> auth.uid()
);

create policy "invitees can read their invites"
on public.room_invites for select to authenticated
using (invitee_id = auth.uid() or inviter_id = auth.uid());

create policy "invitees can delete their invites"
on public.room_invites for delete to authenticated
using (invitee_id = auth.uid());

create policy "inviter can upsert invites"
on public.room_invites for update to authenticated
using (inviter_id = auth.uid())
with check (inviter_id = auth.uid());

-- Storage bucket for images.
insert into storage.buckets (id, name, public)
values ('chat-images', 'chat-images', true)
on conflict (id) do nothing;

create policy "signed in users can upload chat images"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'chat-images'
  and (storage.foldername(name))[1] = auth.uid()::text
);

create policy "public chat images are viewable"
on storage.objects for select to public
using (bucket_id = 'chat-images');

create policy "users can delete their own chat images"
on storage.objects for delete to authenticated
using (
  bucket_id = 'chat-images'
  and owner_id = auth.uid()::text
);

