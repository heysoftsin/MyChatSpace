create table if not exists public.message_reactions(
 message_id bigint not null references public.messages(id) on delete cascade,
 user_id uuid not null references public.profiles(id) on delete cascade,
 reaction text not null check(char_length(reaction)<=16),
 created_at timestamptz not null default now(),
 primary key(message_id,user_id));
create table if not exists public.blocks(
 blocker_id uuid not null references public.profiles(id) on delete cascade,
 blocked_id uuid not null references public.profiles(id) on delete cascade,
 created_at timestamptz not null default now(),
 primary key(blocker_id,blocked_id),check(blocker_id<>blocked_id));
create table if not exists public.reports(
 id bigint generated by default as identity primary key,
 reporter_id uuid not null references public.profiles(id) on delete cascade,
 reported_user_id uuid references public.profiles(id) on delete set null,
 room_id uuid references public.rooms(id) on delete set null,
 message_id bigint references public.messages(id) on delete set null,
 reason text not null,created_at timestamptz not null default now());

alter table public.message_reactions enable row level security;
alter table public.blocks enable row level security;
alter table public.reports enable row level security;

drop policy if exists "members can view reactions" on public.message_reactions;
drop policy if exists "users can react" on public.message_reactions;
create policy "members can view reactions" on public.message_reactions for select to authenticated
using(exists(select 1 from public.messages m where m.id=message_id and public.is_room_member(m.room_id)));
create policy "users can react" on public.message_reactions for insert to authenticated
with check(user_id=auth.uid() and exists(select 1 from public.messages m where m.id=message_id and public.is_room_member(m.room_id)));

drop policy if exists "users manage own blocks" on public.blocks;
create policy "users manage own blocks" on public.blocks for all to authenticated
using(blocker_id=auth.uid()) with check(blocker_id=auth.uid());
drop policy if exists "users create reports" on public.reports;
create policy "users create reports" on public.reports for insert to authenticated with check(reporter_id=auth.uid());

drop policy if exists "users update own messages" on public.messages;
drop policy if exists "users delete own messages" on public.messages;
create policy "users update own messages" on public.messages for update to authenticated
using(sender_id=auth.uid() and public.is_room_member(room_id))
with check(sender_id=auth.uid() and public.is_room_member(room_id));
create policy "users delete own messages" on public.messages for delete to authenticated
using(sender_id=auth.uid() and public.is_room_member(room_id));

